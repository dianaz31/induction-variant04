def f(n):
    return 6 ** (2 * n) - 1

m = 35
bad = []

for n in range(1, 101):
    if f(n) % m != 0:
        bad.append(n)

if not bad:
    print("Контрприкладів не знайдено")
else:
    print("Контрприклади:", bad)